  function ageSet(q, n) {
    var m = n.match(/(?:^|[^а-я])мне\s+([а-я0-9\s]+?)\s+(?:лет|год)/);
    if (!m) return null;
    var toks = m[1].split(' ').filter(Boolean);
    var T_N = { 'двадцат': 20, 'тридцат': 30, 'сорок': 40, 'пятдесят': 50, 'шестдесят': 60, 'семдесят': 70, 'восемдесят': 80, 'девяност': 90 };
    var O_N = { 'один': 1, 'одна': 1, 'одну': 1, 'два': 2, 'две': 2, 'три': 3, 'четыре': 4, 'пят': 5, 'пять': 5, 'шест': 6, 'шесть': 6, 'сем': 7, 'семь': 7, 'восем': 8, 'восемь': 8, 'девят': 9, 'девять': 9, 'одиннадцат': 11, 'двенадцат': 12, 'тринадцат': 13, 'четырнадцат': 14, 'пятнадцат': 15, 'шестнадцат': 16, 'семнадцат': 17, 'восемнадцат': 18, 'девятнадцат': 19 };
    var total = null, ones = null;
    for (var i = 0; i < toks.length; i++) {
      var w = toks[i];
      if (/^\d+$/.test(w)) { total = parseInt(w, 10); continue; }
      if (T_N[w] != null) total = T_N[w];
      else if (O_N[w] != null) ones = O_N[w];
    }
    if (total == null) return null;
    if (ones != null && total % 10 === 0) total += ones;
    if (total < 5 || total > 120) return null;
    window.ZAHAR_USER_AGE = total;
    return 'Записал в тетрадку, ' + nmOr() + ': вам ' + total + '. Теперь и вежливость моя по возрасту выправится.';
  }
